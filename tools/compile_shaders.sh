#!/usr/bin/env bash
# Compiles engine/shaders/*.{vert,frag} to SPIR-V and writes them as uint32_t arrays into
# engine/src/render/vulkan/generated/sprite_spv.h, which is committed so Gradle/CI builds
# never need a shader compiler. Rerun after editing a shader.
#
# Compiler lookup order: $GLSLC, glslc on PATH, the NDK's shader-tools glslc, glslangValidator.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/engine/shaders"
OUT_DIR="$ROOT/engine/src/render/vulkan/generated"
OUT="$OUT_DIR/sprite_spv.h"

find_ndk_glslc() {
    local sdk="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
    [ -n "$sdk" ] || return 1
    local g
    g="$(ls -d "$sdk"/ndk/*/shader-tools/*/glslc 2>/dev/null | sort -V | tail -n 1 || true)"
    [ -n "$g" ] && [ -x "$g" ] && echo "$g"
}

COMPILER="" KIND=""
if [ -n "${GLSLC:-}" ]; then COMPILER="$GLSLC"; KIND=glslc
elif command -v glslc >/dev/null 2>&1; then COMPILER="$(command -v glslc)"; KIND=glslc
elif G="$(find_ndk_glslc)"; then COMPILER="$G"; KIND=glslc
elif command -v glslangValidator >/dev/null 2>&1; then COMPILER="$(command -v glslangValidator)"; KIND=glslang
else
    echo "error: no GLSL compiler found (install glslc / glslang-tools, or set GLSLC)" >&2
    exit 1
fi
echo "Using $COMPILER"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$OUT_DIR"

compile() {   # <stage file> <spv out>
    if [ "$KIND" = glslc ]; then
        "$COMPILER" --target-env=vulkan1.1 -O -o "$2" "$1"
    else
        "$COMPILER" -V --target-env vulkan1.1 -Os -o "$2" "$1" >/dev/null
    fi
    if command -v spirv-val >/dev/null 2>&1; then spirv-val --target-env vulkan1.1 "$2"; fi
}

# Little-endian words, 8 per line. od is POSIX, so no xxd/python needed.
emit_array() {   # <name> <spv>
    local bytes
    bytes=$(wc -c < "$2" | tr -d ' ')
    if [ $((bytes % 4)) -ne 0 ]; then echo "error: $2 is not a whole number of words" >&2; exit 1; fi
    echo "inline constexpr uint32_t $1[] = {"
    od -An -v -t x4 --endian=little "$2" | awk '{ for (i = 1; i <= NF; ++i) printf "%s0x%s,", (n++ % 8 ? " " : "    "), $i; if (n % 8 == 0) printf "\n" } END { if (n % 8) printf "\n" }'
    echo "};"
}

{
    echo "// Generated by tools/compile_shaders.sh from engine/shaders. Do not edit."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo
    echo "namespace mge::render::spv {"
    for f in "$SRC"/*.vert "$SRC"/*.frag; do
        [ -e "$f" ] || continue
        base="$(basename "$f")"
        name="$(echo "$base" | tr '.' '_')"
        compile "$f" "$TMP/$base.spv"
        echo
        emit_array "$name" "$TMP/$base.spv"
    done
    echo
    echo "}  // namespace mge::render::spv"
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "Wrote $OUT"
